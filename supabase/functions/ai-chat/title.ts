// عنوان مرتب لمحادثة المساعد (ونفس المنطق في التطبيق لعنوان ملف PDF)
/** عنوان محادثة مرتب من السؤال: «شرح: …»، «ملخص: …»، «أسئلة: …» */
export function chatTitle(q: string): string {
  let t = q.replace(/\s+/g, ' ').trim().replace(/[؟?.!،]+$/, '');
  let kind = '';
  if (/(اسئل|أسئل|امتحان|اختبار)/.test(t)) kind = 'أسئلة';
  else if (/(لخ[ّ]?ص|ملخص)/.test(t)) kind = 'ملخص';
  else if (/^(?:لو سمحت\s*|رجاء[ًا]?\s*|ممكن\s*)?(?:اشرح|اشرحلي|وضح|وضّح|فسر|فسّر)/.test(t)) kind = 'شرح';
  t = t.replace(/^(?:لو سمحت|رجاء[ًا]?|من فضلك|ممكن|اريد|أريد|ابي|أبي)\s*/, '')
    .replace(/^(?:اشرح|اشرحلي|وضح|وضّح|فسر|فسّر|لخص|لخّص|اعمل|سوي|سوّي|اعطني|أعطني|عطني|اكتب)\s*(?:لي|لنا)?\s*/, '')
    .replace(/^(?:ملخص|ملخصاً|تلخيص)\s*/, '').trim();
  if (kind === 'أسئلة') t = t.replace(/^[\d٠-٩]+\s*/, '').replace(/^(?:اسئلة|أسئلة)\s*(?:امتحانية|وزارية)?\s*(?:متنوعة)?\s*/, '').replace(/^(?:في|عن|من|على)\s+/, '');
  t = t.replace(/\s*مع الإجابات.*$/, '').trim();
  const out = kind ? `${kind}: ${t || 'المنهج'}` : t;
  return out.length > 60 ? `${out.slice(0, 60)}…` : out || 'محادثة جديدة';
}
