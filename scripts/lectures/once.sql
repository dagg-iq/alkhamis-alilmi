-- تصحيح لمرة واحدة (يُشغَّل من lectures-sql.yml عند تغيير هذا الملف): عناوين كررت رقم المحاضرة
-- «المحاضرة ٧ — التغذية والهضم المحاضرة 7» ← «المحاضرة ٧ — التغذية والهضم». آمن لإعادة التشغيل.
update public.lectures
set title = regexp_replace(title, '\s*(محاضرة|المحاضرة)\s*[0-9٠-٩]+\s*$', '')
where title ~ '^المحاضرة [٠-٩]+ — .+(محاضرة|المحاضرة)\s*[0-9٠-٩]+\s*$';
select count(*) as fixed_left from public.lectures where title ~ '^المحاضرة [٠-٩]+ — .+(محاضرة|المحاضرة)\s*[0-9٠-٩]+\s*$';
